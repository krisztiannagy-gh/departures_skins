# Characters drawn as another one (curly quotes, dashes).
ALIAS = {"\u2019": "'", "\u2018": "'", "\u2013": "-", "\u2014": "-"}


NOTICE = "(c) 2019 Sean Petykowski, SIL Open Font License 1.1 - see OFL.txt in the skin's folder on GitHub"


def pack(pictures, height):
    out = {"_h": height, "_c": NOTICE}
    for c, rows in pictures.items():
        assert len(rows) == height, c
        w = len(rows[0])
        out[c] = [w] + [sum(1 << (w - 1 - i) for i, p in enumerate(r) if p == "#") for r in rows]
    return out


def build(here=None):
    here = here or os.path.dirname(os.path.abspath(__file__))
    regular = dict(REGULAR)
    regular.update(EXTRA)
    for a, b in ALIAS.items(): regular[a] = regular[b]
    with open(os.path.join(here, "lu_font.json"), "w") as f:
        json.dump(pack(regular, 10), f, separators=(",", ":"))
    with open(os.path.join(here, "lu_clock.json"), "w") as f:
        json.dump(pack(BOLD, 8), f, separators=(",", ":"))


if __name__ == "__main__":
    build()
