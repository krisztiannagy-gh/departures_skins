# --- stretching helpers ---------------------------------------------------------
def rows9(rows):
    """5x7 -> 9 rows: rows 1 and 5 doubled."""
    out = []
    for i, r in enumerate(rows):
        out.append(r)
        if i in (1, 5): out.append(r)
    return out

def stems(row, w):
    """Double the stem columns: outer columns of wide glyphs, the middle of 3-wide ones."""
    dbl = (1,) if w == 3 else (0, w - 1) if w >= 4 else ()
    return "".join(p * (2 if i in dbl else 1) for i, p in enumerate(row))

# --- line numbers "b" (14 px) and suffix letters "x" (9 px) ---------------------
BIG, SUF = {}, {}
for c, rows in B5.items():
    if not (c.isdigit() or "A" <= c <= "Z" or c in " -"): continue
    w = len(rows[0])
    BIG[c] = [stems(r, w) for r in rows for _ in (0, 1)]
    if "A" <= c <= "Z": SUF[c] = rows9(rows)
BIG[" "] = ["..."] * 14

# --- icons "i" (7 x 7) ----------------------------------------------------------
ICONS = {
    "S": ["..###..", ".#...#.", "##.####", "##...##", "####.##", ".#...#.", "..###.."],   # S-Bahn
    "U": ["..###..", ".#...#.", "#.#.#.#", "#.#.#.#", "#.#.#.#", ".#.#.#.", "..###.."],   # U-Bahn
    "W": ["..#....", ".......", "..###..", ".#.#...", "#..###.", "#....#.", ".###..#"],   # wheelchair
}

# --- U-Bahn font "u" (5 x 9 capitals, 11 rows incl. umlaut dots) ---------------
U = {}
for c, rows in B5.items():
    U[c] = ["." * len(rows[0])] * 2 + rows9(rows)
for c, base in (("Ä", "A"), ("Ö", "O"), ("Ü", "U")):
    U[c] = [".#.#.", "....."] + rows9(B5[base])
U["_"] = ["....."] * 10 + ["#####"]
U["?"] = U.get("?")

def pack(glyphs, h):
    out = {"_h": h}
    for c, rows in glyphs.items():
        if rows is None: continue
        assert len(rows) == h, (c, len(rows))
        w = len(rows[0])
        assert all(len(r) == w for r in rows), c
        out[c] = [w] + ["".join("1" if p == "#" else "0" for p in r) for r in rows]
    return out

def build():
    street = {"s": pack(S, 7), "b": pack(BIG, 14), "x": pack(SUF, 9), "i": pack(ICONS, 7)}
    ubahn = {"u": pack(U, 11)}
    return street, ubahn

if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    street, ubahn = build()
    for name, data in (("wl_street.json", street), ("wl_ubahn.json", ubahn)):
        with open(os.path.join(here, name), "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        print("wrote", name, sum(len(v) - 1 for v in data.values()), "glyphs")
