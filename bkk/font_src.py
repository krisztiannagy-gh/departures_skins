def build():
    out = {"fontheight": 7, "spacing": 1}
    for c, rows in G.items():
        assert len(rows) == 7, c
        w = len(rows[0])
        assert all(len(r) == w for r in rows), c
        out[c] = [w] + ["".join("1" if p == "#" else "0" for p in r) for r in rows]
    return out

if __name__ == "__main__":
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "bkk_font.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(build(), f, ensure_ascii=False, separators=(",", ":"))
    print("wrote", path, len(G), "glyphs")
